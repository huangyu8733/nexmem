/// 内置翻译表的语言代码与词条数，供测试校验各表 key 集合一致。
Map<String, int> get translationTableSizes => <String, int>{
      for (final MapEntry<String, Map<String, String>> entry in _tables.entries)
        entry.key: entry.value.length,
    };

/// 指定语言表中是否包含该 key（测试用）。
bool translationHasKey(String language, String key) =>
    _tables[language]?.containsKey(key) ?? false;

/// 指定语言表的全部 key（测试用）。
Set<String> translationKeys(String language) =>
    _tables[language]?.keys.toSet() ?? const <String>{};

/// 查表：优先精确 locale（如 zh_TW），再语言代码，再英文，最后中文原文。
String lookupTranslation(Locale locale, String key) {
  final String lang = locale.languageCode;
  final String country = locale.countryCode ?? '';
  final String full = country.isEmpty ? lang : '${lang}_$country';
  // 中文原文即翻译 key：简体无独立表，直接回退原文，绝不落入英文表，
  // 否则会把中文界面翻成英文（也保证既有中文测试断言稳定）。
  if (lang == 'zh') {
    return _tables[full]?[key] ?? key;
  }
  for (final String code in <String>[full, lang, 'en']) {
    final Map<String, String>? table = _tables[code];
    final String? value = table?[key];
    if (value != null) return value;
  }
  return key;
}

